LINKS = ("# Links (fixture)\n\n| ID | Name / event | Year |\n|---|---|---|\n"
         "| HL-001 | fixture one | 1843 |\n| HL-002 | fixture two | 1867 |\n| HL-003 | fixture three | 1887 |\n")

ENTRY = '''[[confirmed]]
link = "{link}"
historian = "{historian}"
public = {public}
id = "{id}"
date = "{date}"
title = "Title {id}"
summary = "Summary {id}."
era = "ether"
class = "theory"
thread = ["ether"]
verified = "primary"
checked_by = "Historian"
checked_date = "2026-10-03"
{extra}
  [[confirmed.source]]
  key = "{key}"
  kind = "primary"
'''


def entry(link="HL-001", id="1843-hamilton-quaternions", date="1843-10-16", key="hamilton1865letter",
          historian="confirmed", public="true", extra=""):
    return ENTRY.format(link=link, id=id, date=date, key=key, historian=historian, public=public, extra=extra)


@pytest.fixture
def files(tmp_path, timeline_root):
    tracker = tmp_path / "tracker"
    tracker.mkdir()
    (tracker / "HISTORY-LINKS.md").write_text(LINKS, encoding="utf-8")
    out = tmp_path / "out" / "timeline.toml"

    def run(text, check_only=False, name="HISTORY-CONFIRMED.toml"):
        conf = tracker / name
        conf.write_text(text, encoding="utf-8")
        return ex.export(conf, tracker / "HISTORY-LINKS.md", out, root=timeline_root, check_only=check_only)

    run.out, run.root, run.tracker = out, timeline_root, tracker
    return run


def events(path):
    return tomllib.loads(path.read_text(encoding="utf-8"))["event"]


def test_only_confirmed_and_public_entries_export(files):
    text = (entry() + entry(link="HL-002", id="1867-kelvin-vortex-atoms", date="1867-02-18", key="kelvin1867vortex", public="false")
            + entry(link="HL-003", id="1887-michelson-morley", date="1887-11", key="michelson1887ether", historian="pending"))
    assert files(text) == 0
    assert [e["id"] for e in events(files.out)] == ["1843-hamilton-quaternions"]


def test_a_missing_public_flag_is_skipped(files):
    with pytest.raises(SystemExit, match="nothing to export"):
        files(entry().replace("public = true\n", ""))
    assert not files.out.exists()


