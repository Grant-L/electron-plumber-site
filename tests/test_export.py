def test_a_path_in_an_ignored_folder_of_this_repo_is_refused():
    folder = ROOT / "tools" / "__pycache__"
    folder.mkdir(exist_ok=True)
    path = folder / "HISTORY-CONFIRMED.toml"
    path.write_text(entry(), encoding="utf-8")
