def test_two_runs_are_byte_identical_and_check_passes(files):
    text = entry() + entry(link="HL-003", id="1887-michelson-morley", date="1887-11", key="michelson1887ether")
    files(text)
    first = files.out.read_bytes()
    files(text)
    assert files.out.read_bytes() == first and first.endswith(b"\n") and not first.endswith(b"\n\n") and b"\r" not in first
    assert files(text, check_only=True) == 0


def test_check_fails_after_a_manual_edit(files):
    files(entry())
    files.out.write_text(files.out.read_text(encoding="utf-8").replace("Summary", "Edited"), encoding="utf-8")
    assert files(entry(), check_only=True) == 1


