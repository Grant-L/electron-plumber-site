def test_the_verification_record_dates_bounds_and_claims_cross(files):
    text = (entry(date="1843-10-16", extra='date_basis = "event"\nclaims = ["ep001-c03"]')
            + entry(link="HL-002", id="1850-kelvin", date="", key="kelvin1867vortex",
                    extra='date_basis = "read"\nnot_before = "1845"\nnot_after = "1850"').replace('date = ""\n', "")
            + entry(link="HL-003", id="1887-michelson-morley", date="1887-11", key="michelson1887ether")
            .replace('verified = "primary"', 'verified = "secondary-only"'))
    files(text)
    out = {e["id"]: e for e in events(files.out)}
    assert out["1843-hamilton-quaternions"]["claims"] == ["ep001-c03"]
    assert out["1850-kelvin"]["date_basis"] == "read"
    assert (out["1850-kelvin"]["not_before"], out["1850-kelvin"]["not_after"]) == ("1845", "1850")
    assert out["1887-michelson-morley"]["verified"] == "secondary-only"
    assert all(e["checked_by"] == "Historian" and e["checked_date"] == "2026-10-03" for e in out.values())


